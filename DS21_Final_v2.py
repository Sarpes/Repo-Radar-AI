def grab_col_names(dataframe, cat_th=10, car_th=20):
    """Splits columns into categorical / numerical / categorical-looking-cardinal.

    cat_th : a numeric column with fewer unique values than this is really categorical.
    car_th : an object column with more unique values than this is cardinal (e.g. a name).
    """
    cat_cols = [col for col in dataframe.columns if dataframe[col].dtypes == "O"]
    num_but_cat = [col for col in dataframe.columns
                   if dataframe[col].nunique() < cat_th and dataframe[col].dtypes != "O"]
    cat_but_car = [col for col in dataframe.columns
                   if dataframe[col].nunique() > car_th and dataframe[col].dtypes == "O"]

    cat_cols = cat_cols + num_but_cat
    cat_cols = [col for col in cat_cols if col not in cat_but_car]

    num_cols = [col for col in dataframe.columns if dataframe[col].dtypes != "O"]
    num_cols = [col for col in num_cols if col not in num_but_cat]

    print(f"Observations: {dataframe.shape[0]}")
    print(f"Variables: {dataframe.shape[1]}")
    print(f"cat_cols: {len(cat_cols)}")
    print(f"num_cols: {len(num_cols)}")
    print(f"cat_but_car: {len(cat_but_car)}")
    print(f"num_but_cat: {len(num_but_cat)}")
    return cat_cols, num_cols, cat_but_car


def outlier_thresholds(dataframe, col_name, q1=0.25, q3=0.75):
    """IQR lower/upper bound. Loosening q1/q3 softens the threshold."""
    quartile1 = dataframe[col_name].quantile(q1)
    quartile3 = dataframe[col_name].quantile(q3)
    iqr = quartile3 - quartile1
    return quartile1 - 1.5 * iqr, quartile3 + 1.5 * iqr


def outlier_count(dataframe, col_name, q1=0.25, q3=0.75):
    """Returns the NUMBER of observations outside the bounds.

    The Miuul check_outlier template returns True/False. We need a count here,
    so the name is deliberately different to avoid confusion.
    """
    low, up = outlier_thresholds(dataframe, col_name, q1, q3)
    return dataframe[(dataframe[col_name] < low) | (dataframe[col_name] > up)].shape[0]



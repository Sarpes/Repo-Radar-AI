###############################################################
# AS-OF-T FEATURES - ONE definition, used everywhere
###############################################################
# This existed twice as copy-pasted blocks (the horizon trial in STEP 4 and
# the split comparison in STEP 9) before STEP 11 would have made it three.
# Three definitions of age_at_T is three chances for them to drift apart,
# and the drift would be silent: the script still runs, the numbers just stop
# meaning the same thing.
#
# Every feature here answers "could I have computed this on T?" - the test
# from STEP 3. No counts, no stars, nothing measured after the cutoff.

ASOF_CATEGORICAL = ["language", "license", "ai_category"]


def build_asof_features(frame, cutoff, flags=None):
    """Feature matrix knowable at `cutoff`, for the rows given in `frame`.

    frame  : a slice of df; must still carry the raw text/date columns
    cutoff : the decision moment T
    flags  : uses_* columns to append (defaults to all of them)

    owner_n counts the owner's repos WITHIN `frame`. Since `frame` is always
    the set of repos that existed at `cutoff`, that is the as-of-T portfolio
    size - not today's. Passing a different slice changes its meaning, which
    is why the caller's slice matters and this is not a df-wide lookup.
    """
    flags = [c for c in frame.columns if c.startswith("uses_")] if flags is None else flags
    created_local = pd.to_datetime(frame["created_at"], format="%d/%m/%y")

    X = pd.DataFrame(index=frame.index)
    X["age_at_T"] = (cutoff - created_local).dt.days
    X["topics_n"] = frame["topics"].fillna("").str.split().str.len()
    X["desc_len"] = frame["description"].fillna("").str.len()
    X["name_len"] = frame["name"].str.len()
    X["has_homepage"] = frame["homepage"].notna().astype(int)
    X["owner_n"] = frame["owner"].map(frame["owner"].value_counts())
    for c in flags:
        X[c] = frame[c].values
    for c in ASOF_CATEGORICAL:
        X[c] = frame[c].astype("category")
    return X


def align_by_name(right, left_frame, value_cols):
    """Joins `right` onto `left_frame` BY full_name, never by position.

    The old project measured what positional alignment costs on a filtered
    frame: 14,224 rows became 18,703 with 8,958 NaN, and pandas raised
    nothing. Identity joins cannot do that.
    """
    r = right.set_index("full_name")
    return r.reindex(left_frame["full_name"])[value_cols].set_axis(left_frame.index)



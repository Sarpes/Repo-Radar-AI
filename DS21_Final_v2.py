def cv_auc(splitter, groups=None):
    scores = []
    it = splitter.split(Xg, yg, groups) if groups is not None else splitter.split(Xg, yg)
    for tr, te in it:
        m = LGBMClassifier(n_estimators=400, learning_rate=.05, verbose=-1)
        m.fit(Xg.iloc[tr], yg.iloc[tr])
        scores.append(roc_auc_score(yg.iloc[te], m.predict_proba(Xg.iloc[te])[:, 1]))
    return np.mean(scores), np.std(scores)


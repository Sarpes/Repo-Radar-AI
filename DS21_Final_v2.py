# Compiled once: re.compile in a 23,798-iteration loop is wasted work.
RE_CODE_FENCE = re.compile(r"```")
RE_HEADING = re.compile(r"^#{1,6}\s", re.MULTILINE)
RE_BADGE = re.compile(r"\[!\[")           # [![badge](img)](link) - the shields.io shape
RE_IMAGE = re.compile(r"!\[")
RE_LINK = re.compile(r"(?<!!)\[[^\]]*\]\(")
RE_INSTALL = re.compile(r"(?:^#{1,6}\s*.*install|pip install|npm install|"
                        r"docker run|conda install|uv add|poetry add)",
                        re.IGNORECASE | re.MULTILINE)
RE_CONTRIB = re.compile(r"^#{1,6}\s*.*contribut", re.IGNORECASE | re.MULTILINE)
RE_LICENSE = re.compile(r"^#{1,6}\s*.*licen[cs]e", re.IGNORECASE | re.MULTILINE)
RE_TEST = re.compile(r"pytest|unittest|npm test|\btox\b|coverage|"
                     r"^#{1,6}\s*.*test", re.IGNORECASE | re.MULTILINE)
RE_CITATION = re.compile(r"@article|@inproceedings|bibtex|arxiv\.org|"
                         r"^#{1,6}\s*.*cit(e|ation)", re.IGNORECASE | re.MULTILINE)
RE_DEMO = re.compile(r"huggingface\.co/spaces|colab\.research|"
                     r"\bdemo\b|streamlit\.app|replicate\.com", re.IGNORECASE)


def readme_structure(text):
    """14 structural signals from one README. No content, only shape."""
    n = len(text)
    non_ascii = sum(1 for ch in text if ord(ch) > 127)
    return {
        "readme_var": 1,
        "rm_chars": n,
        "rm_code_blocks": len(RE_CODE_FENCE.findall(text)) // 2,
        "rm_headings": len(RE_HEADING.findall(text)),
        "rm_badges": len(RE_BADGE.findall(text)),
        "rm_images": len(RE_IMAGE.findall(text)),
        "rm_links": len(RE_LINK.findall(text)),
        "rm_has_install": int(bool(RE_INSTALL.search(text))),
        "rm_has_contributing": int(bool(RE_CONTRIB.search(text))),
        "rm_has_license_sec": int(bool(RE_LICENSE.search(text))),
        "rm_has_tests": int(bool(RE_TEST.search(text))),
        "rm_has_citation": int(bool(RE_CITATION.search(text))),
        "rm_has_demo": int(bool(RE_DEMO.search(text))),
        "rm_non_ascii_ratio": non_ascii / max(n, 1),
    }


def build_readme_features(force=False):
    """Parses every README once and caches the result."""
    if os.path.exists(README_FEATURE_PATH) and not force:
        R = pd.read_parquet(README_FEATURE_PATH)
        print(f"cache hit: {README_FEATURE_PATH}  ({len(R):,} rows)")
        return R

    print(f"parsing {len(os.listdir(README_DIR)):,} README files "
          f"(one-off, then cached)...")
    on_disk = set(os.listdir(README_DIR))
    records = []
    t0 = time.time()
    for i, (full_name, fname) in enumerate(zip(df["full_name"], readme_name), 1):
        if fname in on_disk:
            try:
                with open(os.path.join(README_DIR, fname),
                          encoding="utf-8", errors="replace") as fh:
                    rec = readme_structure(fh.read())
            except OSError:
                rec = {"readme_var": 0}
        else:
            # No README is a SIGNAL, not a row to drop (STEP 10: +0.0790).
            rec = {"readme_var": 0}
        rec["full_name"] = full_name
        records.append(rec)
        if i % 5000 == 0:
            print(f"  {i:>6,}/{len(df):,}  ({time.time()-t0:.0f}s)")

    R = pd.DataFrame(records)
    # Repos without a README get 0 for counts. That is deliberate: "no
    # documentation" and "empty documentation" are the same signal here, and
    # readme_var separates them from repos we simply failed to fetch.
    R = R.fillna(0)
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    R.to_parquet(README_FEATURE_PATH, index=False, compression="zstd")
    print(f"parsed in {time.time()-t0:.0f}s -> {README_FEATURE_PATH}")
    return R



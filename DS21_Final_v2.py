def assert_as_of(max_week_used, cutoff=None, label="", weekly=True):
    """Guard 2 - no feature may be built from a week at or after the cutoff.

    max_week_used : the latest week timestamp that fed the aggregate
    cutoff        : the decision moment T
    """
    cutoff = CUTOFF_T if cutoff is None else cutoff
    if pd.isna(max_week_used):
        return True                      # no commit data for this repo: fine
    # AUDIT 2026-09-10 → docs/AUDIT_DEFTERI.md#ds21-final-v2-1765: for WEEKLY buckets, compare the week's END not its
    # AUDIT 2026-09-11 → docs/AUDIT_DEFTERI.md#ds21-final-v2-1770: `weekly` eklendi, cunku ILK SURUM PUSH YOLUNU KIRDI.
    ts = pd.Timestamp(max_week_used)
    son = ts + pd.Timedelta(days=6) if weekly else ts
    if son >= pd.Timestamp(cutoff):
        if weekly:
            raise AssertionError(
                f"LEAKAGE: {label or 'a feature'} used the week starting "
                f"{ts.date()}, which RUNS TO {son.date()} - at or after the "
                f"cutoff T={pd.Timestamp(cutoff).date()}.\n"
                f"A weekly bucket is an INTERVAL: `week < T` is only safe when "
                f"T lands on a week boundary (Sunday)."
            )
        raise AssertionError(
            f"LEAKAGE: {label or 'a feature'} used the event at {ts} - at or "
            f"after the cutoff T={pd.Timestamp(cutoff).date()}.\n"
            f"Event-level windows must use `ts < T`, never `<=`."
        )
    return True



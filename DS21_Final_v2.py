# 4.3  Choosing the horizon
##########################
# The obvious move is to pick the horizon with the best AUC. That is the
# wrong criterion. A short horizon scores well largely because repo age
# alone predicts it - which is nearly a tautology, not a finding.
#
# The better criterion: how much do our ENGINEERED features add ON TOP OF
# age alone? We compare an age-only model against a full metadata model at
# each candidate horizon.

header("STEP 4.2 | Horizon choice - how much do features add over age alone?")

from sklearn.model_selection import GroupKFold
from sklearn.metrics import roc_auc_score
from lightgbm import LGBMClassifier


def horizon_trial(T_h, y, m):
    """Age-only vs full-metadata AUC for one horizon, grouped by owner.
    The label is passed in: STEP 4.5 measures it on the SHIPPED label."""
    d = df[m].copy()
    y = y[m].astype(int)
    X = build_asof_features(d, T_h, USES_FLAGS)     # only features knowable at T_h
    auc_age, auc_full = [], []
    for tr, te in GroupKFold(n_splits=3).split(X, y, groups=d["owner"]):
        m1 = LGBMClassifier(n_estimators=300, learning_rate=0.05, verbose=-1)
        m1.fit(X.iloc[tr][["age_at_T"]], y.iloc[tr])
        auc_age.append(roc_auc_score(y.iloc[te], m1.predict_proba(X.iloc[te][["age_at_T"]])[:, 1]))
        m2 = LGBMClassifier(n_estimators=300, learning_rate=0.05, verbose=-1)
        m2.fit(X.iloc[tr], y.iloc[tr])
        auc_full.append(roc_auc_score(y.iloc[te], m2.predict_proba(X.iloc[te])[:, 1]))
    return len(d), y.mean(), np.mean(auc_age), np.mean(auc_full)



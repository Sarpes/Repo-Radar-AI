###############################################################
# STEP 3: LEAKAGE AUDIT
###############################################################
# This is the most important section of the whole EDA, and the one most
# projects skip. The question is not "which columns correlate?" but:
#
#     "Is this column INFORMATION, or is it my target written differently?"
#
# A dataset with a derived column is a trap: the model finds it, the score
# looks brilliant, and the model has learned arithmetic instead of the world.
#
# We PROVE each rule with a count, we do not assert it. A rule that holds on
# 24,664/24,664 rows is a definition, not a correlation.

header("STEP 3 | LEAKAGE AUDIT")

n = len(df)
leak_report = []


def rule_check(column, description, mask):
    """Records how many rows obey a claimed rule, and prints the verdict."""
    hits = int(mask.sum())
    verdict = "DETERMINISTIC" if hits == n else f"partial ({hits}/{n})"
    leak_report.append({"column": column, "rule": description,
                        "rows_obeying": hits, "verdict": verdict})
    print(f"{column:22s} {hits:6d}/{n}  {verdict:15s}  {description}")
    return hits == n


##########################
# 3.1  Identity and arithmetic
##########################
# The two most dangerous kinds, because they are invisible in a heatmap:
# a perfect copy correlates 1.0 with the target, and a ratio hides its
# numerator inside a plausible-looking "rate" column.

header("STEP 3.1 | Identity and arithmetic rules")

rule_check("watchers", "== stars", df["watchers"] == df["stars"])

# stars_per_day is a float, so we compare with a tolerance rather than ==.
# Floating point division does not round-trip exactly.
computed_spd = df["stars"] / df["repo_age_days"].replace(0, np.nan)
rule_check("stars_per_day", "== stars / repo_age_days",
           (computed_spd - df["stars_per_day"]).abs() < 1e-3)

rule_check("created_year", "== created_at.year",
           df["created_year"] == pd.to_datetime(df["created_at"],
                                                format="%d/%m/%y").dt.year)

# framework_stack: rebuild it from the 17 uses_* flags and compare strings.
USES_FLAGS = [c for c in df.columns if c.startswith("uses_")]
FLAG_NAMES = [c.replace("uses_", "") for c in USES_FLAGS]
flag_matrix = df[USES_FLAGS].values.astype(bool)
rebuilt_stack = [", ".join([nm for nm, on in zip(FLAG_NAMES, row) if on]) or "none detected"
                 for row in flag_matrix]
rule_check("framework_stack", "== join of the 17 uses_* flags",
           pd.Series(rebuilt_stack, index=df.index) == df["framework_stack"])


##########################
# 3.2  Binned columns
##########################
# A "tier"/"status" label is very often just a numeric column cut into
# buckets. The tell: the groups have NON-OVERLAPPING ranges on some column.
# If min/max of each group form a clean, gapless partition, it is a bin.

header("STEP 3.2 | Binned columns - do the group ranges overlap?")

for label_col, source_col in [("popularity_tier", "stars"),
                              ("maintenance_status", "days_since_last_push")]:
    print(f"\n{label_col}  vs  {source_col}")
    g = df.groupby(label_col)[source_col].agg(["min", "max", "count"]).sort_values("min")
    print(g.to_string())
    # Overlap test: sort by min, then every group's min must exceed the
    # previous group's max. If so the label carries no information the
    # source column does not already have.
    overlap = (g["min"].values[1:] <= g["max"].values[:-1]).any()
    print(f"-> ranges overlap: {overlap}   "
          f"{'NOT a pure bin' if overlap else 'PURE BIN -> leakage'}")
    leak_report.append({"column": label_col, "rule": f"bin of {source_col}",
                        "rows_obeying": n if not overlap else -1,
                        "verdict": "DETERMINISTIC" if not overlap else "partial"})


##########################
# 3.3  The rule a correlation heatmap CANNOT catch
##########################
# project_maturity is the subtle one. Its ranges OVERLAP on every single
# column, so no univariate plot and no correlation matrix will flag it.
# It only collapses when two columns are considered JOINTLY.
#
# The technique: fit an unrestricted decision tree using the suspected
# source columns. A tree can express any axis-aligned rule. If it reaches
# 100% TRAINING accuracy, the label is a deterministic function of those
# inputs - there is no noise left to explain.

header("STEP 3.3 | project_maturity - the multi-column rule")

print("Range overlap check (why a heatmap misses this):")
print(df.groupby("project_maturity").agg(
    age_min=("repo_age_days", "min"), age_max=("repo_age_days", "max"),
    stars_min=("stars", "min"), stars_max=("stars", "max"),
    count=("stars", "size")).to_string())

from sklearn.tree import DecisionTreeClassifier, export_text

maturity_inputs = ["stars", "repo_age_days"]
tree = DecisionTreeClassifier(max_depth=5, random_state=42)
tree.fit(df[maturity_inputs], df["project_maturity"])
train_acc = tree.score(df[maturity_inputs], df["project_maturity"])

print(f"\nDecision tree on {maturity_inputs} -> TRAIN accuracy: {train_acc:.4f}")
print("(1.0000 means: not a pattern, a DEFINITION)")
print(export_text(tree, feature_names=maturity_inputs, max_depth=5))

leak_report.append({"column": "project_maturity",
                    "rule": f"f(stars, repo_age_days), tree train acc {train_acc:.4f}",
                    "rows_obeying": int(round(train_acc * n)),
                    "verdict": "DETERMINISTIC" if train_acc == 1.0 else "partial"})



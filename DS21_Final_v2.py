def quick_cv(XX, yy, gg, folds=3, trees=300):
    a = []
    for tr, te in GroupKFold(n_splits=folds).split(XX, yy, gg):
        mm = LGBMClassifier(n_estimators=trees, learning_rate=.05, verbose=-1)
        mm.fit(XX.iloc[tr], yy.iloc[tr])
        a.append(roc_auc_score(yy.iloc[te], mm.predict_proba(XX.iloc[te])[:, 1]))
    return float(np.mean(a))



# WHAT THIS BLOCK IS FOR, AND WHAT IT IS NOT FOR
# The commit series already carries volume, continuity and silence - and it
# carries them for the repo's ENTIRE lifetime. /activity only reaches back to
# ~March 2023 (measured, not assumed), so rebuilding volume features here would
# be both redundant and worse. What /activity has and /stats/contributors does
# NOT: WHO acted, WHERE (which ref), and WHAT KIND of event.
#
# BOT vs HUMAN IS DELIBERATELY ABSENT (decision K8, 2026-09-10). The label is
# `commit in (T, T+180]`, and a dependabot commit IS a commit - the stats API
# does not separate them. A bot-share feature would teach the model to predict
# "will the automation keep running", which is right for this label and
# meaningless for the product. pa_actor_top_share captures the same shape
# WITHOUT needing a definition of "bot": a repo touched only by dependabot
# scores 1.0, and so does a repo touched only by one human. The model learns

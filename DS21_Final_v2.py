# 12.4b  AUDIT | the thresholds are ABSOLUTE, and absolute is sample-conditional
##########################
# STEP 5.5 measured that this corpus is a curated list, not a sample (7.3x density
# cliff at exactly 100 stars; the <100 / 100-1K ratio is 1.01 where a power law
# predicts ~5). The model's probabilities are therefore calibrated to THIS sample's
# base rate, and the badges are absolute cuts on those probabilities.
# Percentile cuts would hold the badge shares steady when the base rate moves.
# NOT switched on: 0.30 / 0.60 are baked into the chatbot footer and the deck, and
# changing badge semantics days before the presentation is a product decision.
BADGE_MODE = "absolute"          # "absolute" | "percentile"

print(f"\nAUDIT | sampling bias vs ABSOLUTE thresholds   (BADGE_MODE = {BADGE_MODE})")
_p = oof[best]
_base = float(y_model.mean())
_lab = ["R", "A", "G"]
_old = pd.cut(_p, [-.01, .30, .60, 1.01], labels=_lab).astype(str)
BADGE_MOVES = {}     # -> model_rapor.json (eda_figures.py F12)
for _pop in [0.25, 0.20, 0.15]:
    _r, _s = _pop / _base, (1 - _pop) / (1 - _base)
    _p2 = (_p * _r) / (_p * _r + (1 - _p) * _s)
    _new = pd.cut(_p2, [-.01, .30, .60, 1.01], labels=_lab).astype(str)
    print(f"  if the true population rate were {_pop:.2f}: "
          f"{int((_old != _new).sum()):,} badges move ({(_old != _new).mean()*100:5.2f}%)")
    BADGE_MOVES[_pop] = float((_old != _new).mean())
print(f"  sample base rate is {_base:.4f}; power-law reweighting implies 0.25-0.29")
print("  rank correlation after prior correction: 1.000000 (monotone transform)")
print("  -> RANKING is immune to sampling bias. Only the cut points are not.")
print("     The percentile switch is one constant, measured and deliberately not taken.")



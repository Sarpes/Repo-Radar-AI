# So the textbook 13-week acceleration is undefined for half the data. Every
# feature here is defined on a SHORT history; no ratio has an unguarded zero
# denominator, no window assumes a year of data exists.

COMMIT_PATH = os.path.join(OUTPUT_DIR, "commit_weeks.parquet")


def build_commit_features(cutoff):
    """As-of-T aggregates from the weekly commit series.

    Returns a frame indexed by full_name. Repos with no pre-cutoff history are
    simply absent - the caller left-joins, so the whole block becomes NaN.
    Missing data is a signal here, as with README (+0.0790) and homepage (+0.2313),
    so the block is left as NaN rather than imputed.

    AUDIT 2026-09-08 - the old claim that an availability flag would be a
    byte-for-byte copy of the NaN pattern was RIGHT about the copy and WRONG
    about the conclusion: that single NaN pools two populations with opposite
    outcomes. The cause is reported in STEP 11c ("fetch flags" line).
    """
    if not os.path.exists(COMMIT_PATH):
        print(f"NOT FOUND: {COMMIT_PATH}")
        print("-> commit features skipped. The pipeline continues without them.")
        return None

    cw = pd.read_parquet(COMMIT_PATH)
    cw["full_name"] = cw["full_name"].astype(str)
    before = len(cw)
    cw = cw[cw["week"] < cutoff].sort_values(["full_name", "week"])
    print(f"weekly rows: {before:,} -> {len(cw):,} after `week < T` "
          f"({before-len(cw):,} dropped as at-or-after the cutoff)")

    g = cw.groupby("full_name", sort=False)
    F = pd.DataFrame(index=g.size().index)

    # --- volume: defined for ANY history length ---
    F["cm_active_weeks"] = g.size()                    # <- expected to be the strongest
    F["cm_total"] = g["commits"].sum()
    F["cm_mean_per_active_week"] = F["cm_total"] / F["cm_active_weeks"]
    F["cm_peak_week"] = g["commits"].max()

    # --- trailing windows ---
    for w in (4, 13, 26, 52):
        lo = cutoff - pd.Timedelta(weeks=w)
        F[f"cm_{w}w"] = (cw[cw["week"] >= lo].groupby("full_name")["commits"]
                         .sum().reindex(F.index).fillna(0).astype(int))

    # --- silence: the HONEST version of the banned days_since_last_push ---
    # Banned was today's value. This is the value at T, which we could have
    # computed on the day. Same idea, legitimate timing.
    last_week = g["week"].max()
    first_week = g["week"].min()
    F["cm_silence_weeks"] = ((cutoff - last_week).dt.days // 7).astype(int)
    F["cm_span_weeks"] = ((last_week - first_week).dt.days // 7).astype(int)
    F["cm_weeks_since_first"] = ((cutoff - first_week).dt.days // 7).astype(int)

    # --- gaps, computed from consecutive ACTIVE weeks ---
    # No zero-filled calendar needed: the distance between two active weeks
    # already encodes the silence between them. A 71-week repo with 19 active
    # weeks needs 19 numbers, not 71.
    gap_weeks = (cw.groupby("full_name")["week"].diff().dt.days // 7) - 1
    gap_weeks = gap_weeks.clip(lower=0)
    gg = gap_weeks.groupby(cw["full_name"])
    F["cm_max_gap"] = gg.max().reindex(F.index).fillna(0)
    F["cm_mean_gap"] = gg.mean().reindex(F.index).fillna(0)

    # --- trend, on a SHORT window so it survives 54% of the data ---
    # cm_4w vs the 9 weeks before it. Denominator guarded with +1 rather than
    # producing inf, because a repo that was silent then active is exactly the
    # interesting case and must not become a missing value.
    F["cm_accel_4w"] = F["cm_4w"] / (F["cm_13w"] - F["cm_4w"] + 1)
    F["cm_recent_share"] = F["cm_13w"] / F["cm_total"].clip(lower=1)

    # --- bus factor: how concentrated is the work on one person? ---
    # `contributors` counts distinct committers IN THAT WEEK, so we cannot get
    # a true unique-person count from it. These are proxies, and honest ones:
    # a project where every active week had exactly one committer is a
    # one-person project regardless of who that person was.
    F["cm_contrib_max"] = g["contributors"].max()
    F["cm_contrib_mean"] = g["contributors"].mean()
    F["cm_solo_week_share"] = (cw["contributors"] == 1).groupby(cw["full_name"]).mean()

    # --- peak timing ---
    peak_idx = g["commits"].idxmax()
    peak_week = cw.loc[peak_idx, "week"].values
    F["cm_weeks_since_peak"] = ((cutoff - pd.Series(peak_week, index=F.index))
                                .dt.days // 7).astype(int)

    # GUARD: prove no feature saw a week at or after the cutoff.
    assert_as_of(cw["week"].max(), cutoff, label="commit aggregates")
    return F



# picking a tool, one is rubbish and the other is exactly what they want.
# coqui-ai/TTS scores 0.20 and is still the best text-to-speech library here.
#
# The fix is NOT to correct the model. P(active) predicts the FUTURE; maturity
# DESCRIBES THE PAST, and the past is observed rather than predicted. So this
# is a RULE, not a second model - and openly a HEURISTIC, because nobody has
# ever labelled repos "finished" vs "abandoned": no ground truth exists.
#
# Thresholds were chosen by measurement, not taste. Five variants were tried;
# the stricter span >= 104 was rejected because it misses
# AUTOMATIC1111/stable-diffusion-webui by four weeks and misses
# google-research/bert entirely, while adding no precision.

header("STEP 13.6 | Maturity - the second axis")

MATURE_SPAN    = 52      # weeks from first commit to last: survived a year
MATURE_COMMITS = 50      # real volume, not a weekend project
MATURE_CONTRIB = 3       # more than one person ever touched it
MATURE_FLOOR   = 0.50    # ranking floor - justified below

# .fillna(False) is deliberate, not incidental: repos with no pre-T commit
# history must NOT be called mature. We cannot see their past, so we do not
# get to vouch for it. Silence about a repo is not evidence in its favour.
# AUDIT 2026-09-14: cm_contrib_max is no longer a model feature (DROP_REDUNDANT) - read from X_commit,
# the pre-drop commit block on the same index, so the rule is unchanged.
is_mature = ((X["cm_span_weeks"]  >= MATURE_SPAN)    &
             (X["cm_total"]       >= MATURE_COMMITS) &
             (X_commit["cm_contrib_max"] >= MATURE_CONTRIB)).fillna(False)

print(f"rule: cm_span_weeks >= {MATURE_SPAN}  AND  cm_total >= {MATURE_COMMITS}"
      f"  AND  cm_contrib_max >= {MATURE_CONTRIB}")
print(f"\nmature: {int(is_mature.sum()):,} / {len(X):,} repos ({is_mature.mean()*100:.1f}%)")
print(f"forced not-mature for want of history: {int(X['cm_span_weeks'].isna().sum()):,}")

##########################
# 13.6.1  Does the rule separate anything, in every band?
##########################
# The rule was designed for the RED band, but it must be checked everywhere.
# If maturity only mattered when P is low, it belongs inside the badge; if it
# separates in all three bands, it is a genuinely independent axis and has to
# be displayed separately. `stars` is BANNED as a model feature - but this is
# not modelling, it is describing observed adoption, so using it here is fair.

header("STEP 13.6.1 | Does maturity separate, band by band?")
mat = np.asarray(is_mature)
print(f"{'band':<14} {'n':>7} {'mature':>7} {'mature%':>8} "
      f"{'med.stars mat':>14} {'not':>7} {'alive mat':>10} {'not':>7}")
for b in ["RED <0.30", "AMBER .30-.60", "GREEN >=0.60"]:
    m = np.asarray(badge == b)
    a, n_ = m & mat, m & ~mat
    print(f"{b:<14} {m.sum():>7,} {a.sum():>7,} {100*mat[m].mean():>7.1f}% "
          f"{np.median(mdf['stars'].values[a]):>14,.0f} "
          f"{np.median(mdf['stars'].values[n_]):>7,.0f} "
          f"{y_model.values[a].mean():>10.3f} {y_model.values[n_].mean():>7.3f}")
print("\n-> maturity separates in ALL THREE bands, not only the red one.")
print("   So it is a second axis, not a correction to the badge: it is shown")
print("   as its own marker next to the badge, never in place of it.")

##########################
# 13.6.2  The ranking floor
##########################
# A badge the user never sees is useless. Under the planned ranking
# (0.7*relevance + 0.3*P), a mature dormant library is buried before anyone
# can read its marker. The floor stops that.
#
# 0.50 is a PRODUCT DECISION, not a measurement, and is presented as one. What
# justifies this particular number is where it lands: 0.50 sits inside the
# AMBER band (0.30-0.60), so a mature repo can never be ranked as RED - and
# never reaches GREEN on maturity alone either. It buys a second look, not a
# recommendation.

header("STEP 13.6.2 | Ranking floor for mature repos (measured, NOT applied)")
p_final = oof[best]
p_floor = np.where(mat, np.maximum(p_final, MATURE_FLOOR), p_final)
lifted = p_floor != p_final

print(f"a floor of {MATURE_FLOOR:.2f} on mature repos would lift:")
print(f"  lifted: {lifted.sum():,} repos ({100*lifted.mean():.1f}% of all)")
print(f"    from RED   {int((np.asarray(badge == 'RED <0.30') & lifted).sum()):,}"
      f"  -> they leave the red band entirely")
print(f"    within AMBER {int((np.asarray(badge == 'AMBER .30-.60') & lifted).sum()):,}"
      f"  -> band unchanged, rank improves")
print(f"\nSANITY: are the lifted repos really more alive than their band?")
print(f"  lifted repos actually alive   {y_model.values[lifted].mean():.3f}")
print(f"  RED band overall              {y_model.values[np.asarray(badge == 'RED <0.30')].mean():.3f}")
_lift_rate = y_model.values[lifted].mean()
print(f"  -> they revive more often than RED, but a {MATURE_FLOOR:.2f} floor would overstate them "
      f"{MATURE_FLOOR / _lift_rate:.1f}x. NOT applied (13.09, DS_BULGULAR B7): is_mature stays a marker.")


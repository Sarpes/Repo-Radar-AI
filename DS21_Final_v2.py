PUSH_COMPLETE_FROM = pd.Timestamp("2025-03-11")   # HEDEF_TARIH, n8n/build_tarihce_workflow.py:73


def build_push_features(cutoff):
    """As-of-T aggregates from the raw /activity event stream.

    Returns a frame indexed by full_name. Repos with no pre-cutoff events are
    absent - the caller left-joins, so the block becomes NaN.
    """
    if not os.path.exists(PUSH_PATH):
        print(f"NOT FOUND: {PUSH_PATH}")
        print("-> push features skipped. The pipeline continues without them.")
        return None

    pe = pd.read_parquet(PUSH_PATH)
    before = len(pe)
    lo = cutoff - pd.Timedelta(weeks=PA_WINDOW_WEEKS)
    assert lo >= PUSH_COMPLETE_FROM, f"pa_* window starts {lo.date()}, before complete data"
    pe = pe[(pe["ts"] >= lo) & (pe["ts"] < cutoff)]
    print(f"events: {before:,} -> {len(pe):,} in [{lo.date()}, T) "
          f"({PA_WINDOW_WEEKS}-week window, complete for every non-capped repo)")
    if not len(pe):
        return None

    name = pe["full_name"]
    g = pe.groupby("full_name", sort=False)
    n = g.size()
    F = pd.DataFrame(index=n.index)

    # --- A | WHO ---
    F["pa_events"] = n
    F["pa_actors_distinct"] = g["actor"].nunique()
    # Share held by the single busiest actor. 1.0 means one source did
    # everything - a one-person project or a bot-only repo, and the model is
    # free to decide whether those are the same risk.
    busiest = pe.groupby(["full_name", "actor"]).size().groupby(level=0).max()
    F["pa_actor_top_share"] = busiest / n

    # --- B | WHERE ---
    # Work on the default branch is the project moving; work elsewhere may be a
    # docs deploy (gh-pages) or a bot's update branch.
    # KNOWN LIMIT (measured 2026-09-10): this treats main/master as THE default
    # branch. 37 repos in the label study use develop/dev/ts instead, and their
    # real default_branch is available in the metadata fetch. Fixing it is a
    # post-presentation item; as a FEATURE the mislabel is a shift, not a lie -
    # unlike as a LABEL, where it would have marked live repos dead.
    F["pa_default_ref_share"] = pe["ref"].isin(DEFAULT_REFS).groupby(name).mean()
    F["pa_refs_distinct"] = g["ref"].nunique()

    # --- C | WHAT KIND ---
    # pr_merge is the closest thing in this stream to "a human reviewed and
    # accepted a change". Branch churn without pr_merge is the CI signature -
    # measured on 30 group-A repos: branch_creation 100, push 66, pr_merge 5.
    F["pa_pr_merge_share"] = pe["kind"].eq("pr_merge").groupby(name).mean()
    F["pa_force_push_share"] = pe["kind"].eq("force_push").groupby(name).mean()
    F["pa_branch_churn"] = pe["kind"].isin(CHURN_KINDS).groupby(name).mean()

    assert_as_of(pe["ts"].max(), cutoff, label="push aggregates",
                 weekly=False)   # olay damgasi, haftalik kova DEGIL
    return F


